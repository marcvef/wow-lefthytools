// Regenerates LefthyTools/Data/MinimapTiles.lua: the file ID of every minimap tile of the two
// continents, for the fight stream's map (Modules/Beacon/Stream.lua draws the tiles around you).
//
// A minimap tile is world/minimaps/<continent>/map<X>_<Y>.blp, 256 px for 533.33 yd of the world's
// grid: X = floor(32 - west / 533.33), Y = floor(32 - north / 533.33). The client draws the minimap
// itself, but the tiles are ordinary texture files: an addon shows them by file ID.
//
// Source: wago.tools' file list of a Forever build (only the files that build has). Run it when
// Forever gets new builds:
//   node tools/update-minimap-tiles.js                 the latest Forever build
//   node tools/update-minimap-tiles.js 1.60.1.70291
const fs = require("fs");
const path = require("path");

const CONTINENTS = { 0: "azeroth", 1: "kalimdor" }; // UnitPosition's instance ID -> folder

async function latestBuild() {
  const builds = await (await fetch("https://wago.tools/api/builds")).json();
  // WoW: Forever is version 1.60.x (listed under a beta product on wago.tools).
  const all = Object.values(builds).flat().map((b) => b.version).filter((v) => /^1\.60\./.test(v));
  const key = (v) => v.split(".").map((n) => n.padStart(8, "0")).join(".");
  return all.sort((a, b) => (key(a) < key(b) ? 1 : -1))[0];
}

async function tiles(folder, build) {
  const url = `https://wago.tools/api/files?search=world/minimaps/${folder}/map&version=${build}`;
  const list = await (await fetch(url)).json();
  const out = [];
  for (const [id, name] of Object.entries(list)) {
    const m = name.match(new RegExp(`^world/minimaps/${folder}/map(\\d+)_(\\d+)\\.blp$`));
    if (m) out.push([Number(m[1]), Number(m[2]), Number(id)]);
  }
  return out.sort((a, b) => a[0] - b[0] || a[1] - b[1]);
}

(async () => {
  const build = process.argv[2] || (await latestBuild());
  const lines = [
    "local _, ns = ...",
    "",
    `-- Generated by tools/update-minimap-tiles.js from Forever build ${build}: don't edit by hand.`,
    "-- ns.MINIMAP_TILES[continent][X * 100 + Y] = the file ID of world/minimaps/<continent>/mapX_Y.blp",
    "-- (continent: UnitPosition's instance ID, 0 Eastern Kingdoms, 1 Kalimdor).",
    "ns.MINIMAP_TILES = {",
  ];
  let total = 0;
  for (const [continent, folder] of Object.entries(CONTINENTS)) {
    const list = await tiles(folder, build);
    if (list.length === 0) throw new Error(`no minimap tiles for ${folder} in ${build}`);
    total += list.length;
    lines.push(`\t[${continent}] = { -- ${folder}, ${list.length} tiles`);
    for (let i = 0; i < list.length; i += 6) {
      lines.push("\t\t" + list.slice(i, i + 6).map(([x, y, id]) => `[${x * 100 + y}] = ${id},`).join(" "));
    }
    lines.push("\t},");
  }
  lines.push("}", "");
  const file = path.join(__dirname, "..", "LefthyTools", "Data", "MinimapTiles.lua");
  fs.writeFileSync(file, lines.join("\n"));
  console.log(`${total} tiles from ${build} -> ${path.relative(process.cwd(), file)}`);
})().catch((e) => {
  console.error(e.message || e);
  process.exit(1);
});

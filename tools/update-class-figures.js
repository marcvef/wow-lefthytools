// Regenerates LefthyTools/Data/ClassFigures.lua: a figure for each class, race and sex, for the fight
// stream's battle row (Modules/Beacon/StreamBattle.lua). A friend whose character your client doesn't
// have (not near you) can't be shown as they look (the game shows nobody's face, skin or gear from
// afar), so they're a figure of their class instead: an NPC who trains it, of their race and sex when
// there is one. Display IDs (CreatureDisplayInfo), shown with SetDisplayInfo: textured, dressed.
//
// Sources: which NPCs train which class, from a classic world database's creature_template
// (TrainerType 0, TrainerClass; by default CMaNGOS Classic DB's full dump, the same as
// tools/update-drop-data.js: only these facts are taken, the NPCs' model IDs); each model's race and
// sex from the client's CreatureDisplayInfo and CreatureDisplayInfoExtra (wago.tools). The first
// trainer of each kind (the lowest creature ID: starting zones first) is the one.
//   node tools/update-class-figures.js [dump.sql[.gz]] [--build 1.60.1.70425] [--cache <dir>]
const fs = require("fs");
const path = require("path");
const zlib = require("zlib");
const { rows } = require("./update-drop-data.js");

const DUMP_URL = "https://raw.githubusercontent.com/cmangos/classic-db/master/Full_DB/ClassicDB_1_12_1_z2815.sql.gz";
const OUT = path.join(__dirname, "..", "LefthyTools", "Data", "ClassFigures.lua");
const CLASSES = { 1: "WARRIOR", 2: "PALADIN", 3: "HUNTER", 4: "ROGUE", 5: "PRIEST", 7: "SHAMAN", 8: "MAGE", 9: "WARLOCK", 11: "DRUID" };

function parseCsv(text) {
  const lines = text.split(/\r?\n/).filter(Boolean);
  const head = lines[0].split(",");
  return lines.slice(1).map((l) => {
    const v = l.split(",");
    return Object.fromEntries(head.map((h, i) => [h, v[i]]));
  });
}

async function latestBuild() {
  const builds = await (await fetch("https://wago.tools/api/builds")).json();
  const all = Object.values(builds).flat().map((b) => b.version).filter((v) => /^1\.60\./.test(v));
  const key = (v) => v.split(".").map((n) => n.padStart(8, "0")).join(".");
  return all.sort((a, b) => (key(a) < key(b) ? 1 : -1))[0];
}

async function table(name, build, cache) {
  const file = cache && path.join(cache, `${name}-${build}.csv`);
  let text;
  if (file && fs.existsSync(file)) {
    text = fs.readFileSync(file, "utf8");
  } else {
    const response = await fetch(`https://wago.tools/db2/${name}/csv?build=${build}`);
    if (!response.ok) throw new Error(`${name}: HTTP ${response.status}`);
    text = await response.text();
    if (file) fs.writeFileSync(file, text);
  }
  return parseCsv(text);
}

async function dumpText(arg) {
  if (arg) {
    const data = fs.readFileSync(arg);
    return arg.endsWith(".gz") ? zlib.gunzipSync(data).toString("utf8") : data.toString("utf8");
  }
  console.log(`downloading ${DUMP_URL}`);
  const response = await fetch(DUMP_URL);
  if (!response.ok) throw new Error(`download failed: ${response.status}`);
  return zlib.gunzipSync(Buffer.from(await response.arrayBuffer())).toString("utf8");
}

async function main() {
  const args = process.argv.slice(2);
  const opt = (name) => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : null; };
  const cache = opt("--cache");
  if (cache) fs.mkdirSync(cache, { recursive: true });
  const dump = args.find((a, i) => !a.startsWith("--") && !["--build", "--cache"].includes(args[i - 1]));
  const build = opt("--build") || (await latestBuild());
  console.log(`build ${build}`);

  const creatures = rows(await dumpText(dump), "creature_template");
  const displays = new Map((await table("CreatureDisplayInfo", build, cache)).map((d) => [d.ID, d]));
  const extras = new Map((await table("CreatureDisplayInfoExtra", build, cache)).map((e) => [e.ID, e]));

  const trainers = creatures.filter((c) => c.TrainerType === 0 && CLASSES[c.TrainerClass]).sort((a, b) => a.Entry - b.Entry);
  const figures = {}; // class -> race -> [male, female]
  let used = 0;
  for (const c of trainers) {
    for (const model of [c.ModelId1, c.ModelId2, c.ModelId3, c.ModelId4]) {
      const display = model && displays.get(String(model));
      const extra = display && display.ExtendedDisplayInfoID !== "0" && extras.get(display.ExtendedDisplayInfoID);
      if (!extra) continue;
      const cls = CLASSES[c.TrainerClass], race = +extra.DisplayRaceID, sex = +extra.DisplaySexID;
      if (!race || (sex !== 0 && sex !== 1)) continue;
      figures[cls] = figures[cls] || {};
      figures[cls][race] = figures[cls][race] || [0, 0];
      if (!figures[cls][race][sex]) {
        figures[cls][race][sex] = model;
        used++;
      }
    }
  }
  const lines = [
    "-- Generated by tools/update-class-figures.js: don't edit, run the tool again.",
    `-- A figure for each class, race and sex (display IDs): an NPC who trains the class (which NPCs train`,
    `-- which class: a classic world database, CMaNGOS Classic DB; their race and sex: the client's`,
    `-- CreatureDisplayInfoExtra, ${build}). [race] = { male, female }, 0 where there's none.`,
    "local _, ns = ...",
    "ns.CLASS_FIGURES = {",
  ];
  for (const cls of Object.values(CLASSES)) {
    const races = figures[cls] || {};
    const parts = Object.keys(races).map(Number).sort((a, b) => a - b).map((r) => `[${r}] = { ${races[r][0]}, ${races[r][1]} }`);
    lines.push(`\t${cls} = { ${parts.join(", ")} },`);
  }
  lines.push("}", "");
  console.log(`${trainers.length} trainers, ${used} figures`);
  for (const cls of Object.values(CLASSES)) {
    console.log(cls.padEnd(8), Object.entries(figures[cls] || {}).map(([r, v]) => `${r}:${v[0] ? "m" : "-"}${v[1] ? "f" : "-"}`).join(" "));
  }
  if (args.includes("--stats")) return;
  fs.writeFileSync(OUT, lines.join("\n"));
  console.log(`written: ${path.relative(process.cwd(), OUT)}`);
}

main().catch((e) => { console.error(e.message); process.exit(1); });

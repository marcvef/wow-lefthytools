// Regenerates LefthyTools/Data/MapOverlays.lua: every explorable area's art of each zone map (the
// overlays the world map lays over a zone's art where you've explored), for maps of ours that show a
// zone uncovered (Core/MapArt.lua's reveal: Questtree's maps).
//
// The world map draws a zone's art (UiMapArtTile) with its fog, and over it an overlay per area you've
// explored (C_MapExplorationInfo.GetExploredMapTextures: only the explored ones). Every overlay is in
// the client's tables: WorldMapOverlay (its art map, size and offset in the art's pixels, flags) and
// WorldMapOverlayTile (its texture files by row and column). Overlays behind a player condition (a
// phase) are left out, and so are those shown only on mouseover.
//
// Source: wago.tools' exports of a Forever build's client tables. Run it when Forever gets new builds:
//   node tools/update-map-overlays.js                 the latest Forever build
//   node tools/update-map-overlays.js 1.60.1.70888 [--cache <dir>]
const fs = require("fs");
const path = require("path");
const { table, options } = require("./wago");

const MOUSEOVER = 0x2; // WorldMapOverlay.Flags: shown only while the mouse is over its area
const ON_TOP = 0x4;    // drawn over the other overlays (MapArt's isDrawOnTopLayer)
const OUT = path.join(__dirname, "..", "LefthyTools", "Data", "MapOverlays.lua");

(async () => {
  const { build, cache } = await options();
  const overlays = await table("WorldMapOverlay", build, cache);
  const tiles = await table("WorldMapOverlayTile", build, cache);
  const maps = await table("UiMapXMapArt", build, cache);

  const filesOf = new Map(); // overlay ID -> [[row, col, file]]
  for (const t of tiles) {
    if (Number(t.LayerIndex) !== 0) continue;
    if (!filesOf.has(t.WorldMapOverlayID)) filesOf.set(t.WorldMapOverlayID, []);
    filesOf.get(t.WorldMapOverlayID).push([Number(t.RowIndex), Number(t.ColIndex), Number(t.FileDataID)]);
  }
  const byArt = new Map(); // art ID -> ["w:h:x:y:top:file,file"]
  let count = 0;
  for (const o of overlays.sort((a, b) => Number(a.ID) - Number(b.ID))) {
    const flags = Number(o.Flags);
    if (Number(o.PlayerConditionID) !== 0 || flags & MOUSEOVER) continue;
    const list = filesOf.get(o.ID);
    if (!list || !list.length) continue;
    list.sort((a, b) => a[0] - b[0] || a[1] - b[1]);
    const files = list.map((f) => f[2]).join(",");
    const art = Number(o.UiMapArtID);
    if (!byArt.has(art)) byArt.set(art, []);
    byArt.get(art).push([o.TextureWidth, o.TextureHeight, o.OffsetX, o.OffsetY, flags & ON_TOP ? 1 : 0, files].join(":"));
    count++;
  }
  const lines = [
    "local _, ns = ...",
    "",
    `-- Generated by tools/update-map-overlays.js from Forever build ${build} (wago.tools): don't edit by hand.`,
    "-- ns.MAP_OVERLAYS[art] = \"width:height:offsetX:offsetY:onTop:file,file,...;...\": every explorable area's",
    "-- overlay on a zone's map art (C_Map.GetMapArtID), in the art's pixels, its tiles by rows (Core/MapArt.lua).",
    "-- ns.MAP_ART[uiMapID] = the map's art, where the game's C_Map.GetMapArtID doesn't answer.",
    "ns.MAP_OVERLAYS = {",
  ];
  for (const art of [...byArt.keys()].sort((a, b) => a - b)) lines.push(`\t[${art}] = "${byArt.get(art).join(";")}",`);
  lines.push("}");
  lines.push("ns.MAP_ART = {");
  for (const m of maps.sort((a, b) => Number(a.UiMapID) - Number(b.UiMapID))) {
    if (Number(m.PhaseID) === 0) lines.push(`\t[${m.UiMapID}] = ${m.UiMapArtID},`);
  }
  lines.push("}");
  fs.writeFileSync(OUT, lines.join("\n") + "\n");
  console.log(`${OUT}: ${count} overlays on ${byArt.size} maps (${build})`);
})().catch((e) => {
  console.error(e.message);
  process.exit(1);
});
